const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
  const desktop = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await desktop.route('**/*', route => route.request().method() === 'GET' && new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const page = await desktop.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:3100/review', { waitUntil: 'networkidle' });
  assert(await page.getByRole('heading', { name: 'A more dimensional Sunforge.' }).isVisible());
  assert(await page.locator('img').evaluateAll(images => images.filter(i => i.loading !== 'lazy').every(i => i.complete && i.naturalWidth > 0)));
  assert.equal((await page.request.get('http://127.0.0.1:3100/review-assets/review-motion.webm')).status(), 200);
  await page.screenshot({ path: 'review/gallery-desktop.png' });
  await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle' });
  await page.locator('#front-desk').scrollIntoViewIfNeeded(); await page.waitForTimeout(800);
  await page.locator('#front-desk').screenshot({ path: 'review/desktop-service.png', style: '.sf-navigation, .sf-review-bar { visibility: hidden !important; }' });
  fs.copyFileSync('review/desktop-service.png', 'public/review-assets/desktop-service.png');
  const touch = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  await touch.route('**/*', route => route.request().method() === 'GET' && new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const mobile = await touch.newPage(); mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle' });
  await mobile.getByRole('button', { name: 'View call summary' }).tap();
  assert(await mobile.locator('#sf-summary-detail').isVisible());
  const overlap = await mobile.evaluate(() => {
    const phone = document.querySelector('.sf-phone').getBoundingClientRect();
    const notification = document.querySelector('.sf-notification').getBoundingClientRect();
    return phone.bottom > notification.top;
  });
  assert(!overlap, 'Mobile content panels do not overlap');
  await mobile.getByRole('button', { name: 'Close call summary' }).tap();
  await mobile.setViewportSize({ width: 768, height: 1024 });
  await mobile.evaluate(() => scrollTo(0, 0)); await mobile.waitForTimeout(800);
  assert((await mobile.locator('.sf-navigation nav > a img').boundingBox()).width > 100, 'Tablet logo remains visible');
  await mobile.getByRole('button', { name: 'Open navigation menu' }).tap();
  assert(await mobile.locator('#site-navigation-menu').isVisible());
  await mobile.getByRole('button', { name: 'Close navigation menu' }).tap();
  await mobile.screenshot({ path: 'review/tablet-prototype.png' });
  assert.equal(errors.length, 0);
  console.log('PASS: gallery assets and video, production routes, touch interaction, non-overlapping mobile panels, no page errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
